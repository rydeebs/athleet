import {withBrandIdentity} from '../brand.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import worker from '../dist/server/index.js';
test('campaign planning is directly readable and exposes a local brief with no invented prices',async()=>{
 for(const path of ['/for-sponsors','/for-sponsors/','/sponsor.js'])assert.equal((await worker.fetch(new Request('https://example.com'+path))).status,200);
 const page=await (await worker.fetch(new Request('https://example.com/for-sponsors'))).text();
 assert.match(page,/A brief you can agree/);
 assert.match(page,/example package structures, not live offers/);
 assert.match(page,/not sent, booked or paid/);
 assert.doesNotMatch(page,/\$\s*\d|Marketplace concept|Sponsor package concept|season-dialog/);
 for(const name of ['brand','weekends','market','offer'])assert.ok(page.includes(`name="${name}"`));
 for(const id of ['packages','season','season-form','season-status'])assert.ok(page.includes(`id="${id}"`));
 assert.ok(page.includes('href="/sponsors?workspace=1"'));
 const vercel=JSON.parse(await readFile('vercel.json','utf8'));
 assert.ok(vercel.rewrites.some(r=>r.source==='/for-sponsors'&&r.destination==='/sponsor.html'));
 assert.equal(await readFile('dist/public/sponsor.html','utf8'),withBrandIdentity(await readFile('sponsor.html','utf8')));
 assert.ok((await readFile('index.html','utf8')).includes('href="/for-sponsors">For sponsors'));
});
